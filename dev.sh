# The subset of the suite that needs no Testcontainers/Docker — verified by
# running it in this environment (no Docker daemon available here) on
# 2026-09-25. IngestionServiceTest and IdempotencyTest are deliberately
# excluded: both need a real Spring context backed by Testcontainers

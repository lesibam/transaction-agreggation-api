cmd_perf() {
  # Defaults match scripts/load-test.js's own env-var contract (LOAD_TEST_*),
  # not a wrapper-invented one - see that script's header comment for the
  # full set (LOAD_TEST_RAMP/HOLD, SOAK_VUS/DURATION) if you need finer
  # control than these flags expose; just export them before calling perf.
  local scenario=smoke vus=20 hold=2m customer_id="$DEFAULT_CUSTOMER_ID" tls=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --scenario) scenario="$2"; shift 2 ;;
      --vus) vus="$2"; shift 2 ;;
      --hold) hold="$2"; shift 2 ;;
      --customer-id) customer_id="$2"; shift 2 ;;
      --tls) tls=1; shift ;;
      *) log_err "Unknown option for perf: $1"; exit 1 ;;
    esac
  done

  compose_context "$tls"
  load_env

  if ! curl -fsS $CURL_TLS_FLAG "$BASE_URL/actuator/health" >/dev/null 2>&1; then
    log_err "API not reachable at $BASE_URL. Start it first: ./dev.sh start"
    exit 1
  fi

  log_info "Running scripts/load-test.js: SCENARIO=$scenario LOAD_TEST_VUS=$vus LOAD_TEST_HOLD=$hold BASE_URL=$BASE_URL"
  log_info "Default scenario is 'smoke' (fast pipeline sanity, ~10s) - pass --scenario load|soak|all" \
           "for a real capacity run. Deliberately not wired into CI (shared-runner timings are noise" \
           "for a p99 SLO); see IMPLEMENTATION_PLAN.md Phase 7 for the last verified numbers."

  # The script mints its own token in setup() if LOAD_TEST_TOKEN is absent,
  # using LOAD_TEST_JWT_SECRET (or a test-only default that won't match a
  # real running server). Pass the real secret explicitly so it mints
  # against whatever this stack is actually using - same reasoning as the
  # mint-jwt.mjs fallback warning (L-03).
  if command -v k6 >/dev/null 2>&1; then
    LOAD_TEST_BASE_URL="$BASE_URL" LOAD_TEST_CUSTOMER_ID="$customer_id" \
      LOAD_TEST_JWT_SECRET="$APP_SECURITY_JWT_SECRET" \
      SCENARIO="$scenario" LOAD_TEST_VUS="$vus" LOAD_TEST_HOLD="$hold" \
      k6 run "$ROOT/scripts/load-test.js"
  else
    log_info "Local k6 binary not found — running via the official grafana/k6 Docker image."
    local docker_base_url="$BASE_URL"
    if [[ "$BASE_URL" == *localhost* ]]; then
      docker_base_url="${BASE_URL/localhost/host.docker.internal}"
    fi
    docker run --rm -i \
      --add-host=host.docker.internal:host-gateway \
      -e LOAD_TEST_BASE_URL="$docker_base_url" -e LOAD_TEST_CUSTOMER_ID="$customer_id" \
      -e LOAD_TEST_JWT_SECRET="$APP_SECURITY_JWT_SECRET" \
      -e SCENARIO="$scenario" -e LOAD_TEST_VUS="$vus" -e LOAD_TEST_HOLD="$hold" \
      -v "$ROOT/scripts:/scripts:ro" \
      grafana/k6 run /scripts/load-test.js
  fi
}


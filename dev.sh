cmd_setup() {
  log_info "Checking prerequisites..."
  require_cmd docker "Install Docker Desktop / Docker Engine."
  if ! docker compose version >/dev/null 2>&1; then
    log_err "'docker compose' (v2 plugin) is required. Update Docker Desktop/Engine."
    exit 1
  fi
  require_cmd java "Install JDK 21+."
  require_cmd mvn "Install Maven 3.9+ (or use ./scripts/test.sh which wraps mvn)."
  require_cmd node "Install Node.js (used for JWT minting and Playwright/k6 helpers)."
  require_cmd openssl "Install openssl (used for .env secrets and ./dev.sh certs)."
  if ! command -v jq >/dev/null 2>&1; then
    log_warn "jq not found — 'status' and 'seed' output will be less readable, but will still work."
  fi
  log_ok "Prerequisites OK."

  ensure_env_file

  log_info "Building the application image (docker compose build transaction-api)..."
  compose_context 0
  compose build transaction-api

  log_ok "Setup complete. Next: ./dev.sh start"
}

# ---------------------------------------------------------------------------
# certs
# ---------------------------------------------------------------------------

cmd_certs() {
  local force=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --force) force=1; shift ;;
      *) log_err "Unknown option for certs: $1"; exit 1 ;;
    esac
  done

  require_cmd openssl "Install openssl."

  if [[ -f "$CERT_DIR/localhost.p12" && "$force" -eq 0 ]]; then
    log_info "Certs already exist at $CERT_DIR (use --force to regenerate)."
    return 0
  fi

  mkdir -p "$CERT_DIR"
  chmod 700 "$CERT_DIR"

  log_info "Generating local dev CA + server certificate for localhost (self-signed, dev-only)..."

  openssl req -x509 -new -nodes -newkey rsa:4096 -sha256 -days 825 \
    -keyout "$CERT_DIR/dev-ca.key" -out "$CERT_DIR/dev-ca.crt" \
    -subj "/CN=Transact Local Dev CA" >/dev/null 2>&1

  openssl req -new -nodes -newkey rsa:2048 \
    -keyout "$CERT_DIR/localhost.key" -out "$CERT_DIR/localhost.csr" \
    -subj "/CN=localhost" >/dev/null 2>&1

  openssl x509 -req -in "$CERT_DIR/localhost.csr" \
    -CA "$CERT_DIR/dev-ca.crt" -CAkey "$CERT_DIR/dev-ca.key" -CAcreateserial \
    -out "$CERT_DIR/localhost.crt" -days 825 -sha256 \
    -extfile <(printf "subjectAltName=DNS:localhost,DNS:transaction-api,IP:127.0.0.1") \
    >/dev/null 2>&1

  local keystore_password
  keystore_password="$(openssl rand -hex 16)"

  openssl pkcs12 -export \
    -in "$CERT_DIR/localhost.crt" -inkey "$CERT_DIR/localhost.key" \
    -certfile "$CERT_DIR/dev-ca.crt" -name transact \
    -out "$CERT_DIR/localhost.p12" -password "pass:$keystore_password" \
    >/dev/null 2>&1

  rm -f "$CERT_DIR/localhost.csr" "$CERT_DIR/dev-ca.srl"
  chmod 600 "$CERT_DIR"/*.key "$CERT_DIR/localhost.p12" 2>/dev/null || true

  ensure_env_file
  if grep -q '^SERVER_SSL_KEY_STORE_PASSWORD=' "$ENV_FILE" 2>/dev/null; then
    # Replace any previous value (e.g. after --force regeneration).
    local tmp
    tmp="$(mktemp)"
    grep -v '^SERVER_SSL_KEY_STORE_PASSWORD=' "$ENV_FILE" > "$tmp"
    mv "$tmp" "$ENV_FILE"
  fi
  echo "SERVER_SSL_KEY_STORE_PASSWORD=$keystore_password" >> "$ENV_FILE"

  log_ok "Certs written to $CERT_DIR (gitignored). Keystore password stored in .env."
  log_warn "Local dev only: self-signed, API listener only. Postgres/Kafka stay plaintext" \
           "(IMPLEMENTATION_PLAN.md Phase 9, not delivered). Use './dev.sh start --tls' to try it."
}

# ---------------------------------------------------------------------------
# start / stop / restart / status / logs
# ---------------------------------------------------------------------------

cmd_start() {
  local build=0 tls=0 wait_timeout=300
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --build) build=1; shift ;;
      --tls) tls=1; shift ;;
      --wait-timeout) wait_timeout="$2"; shift 2 ;;
      *) log_err "Unknown option for start: $1"; exit 1 ;;
    esac
  done

  ensure_env_file
  [[ "$tls" -eq 1 ]] && require_certs
  compose_context "$tls"

  local up_args=(up -d --wait --wait-timeout "$wait_timeout")
  [[ "$build" -eq 1 ]] && up_args+=(--build)

  log_info "Starting stack (${COMPOSE_FILES[*]})..."
  compose "${up_args[@]}"

  log_ok "Stack is up."
  print_ready_banner "$tls"
}

print_ready_banner() {
  local tls="$1"
  compose_context "$tls"
  echo
  echo "  API           $BASE_URL"
  echo "  Health        $BASE_URL/actuator/health"
  echo "  Prometheus    http://localhost:9090"
  echo "  Grafana       http://localhost:3000  (admin/admin — dev-only default creds)"
  if [[ "$tls" -eq 1 ]]; then
    echo "  (TLS is self-signed — curl needs -k, browsers need a security bypass/CA import)"
  fi
  if [[ -f "$ENV_FILE" ]] && command -v node >/dev/null 2>&1; then
    load_env
    echo
    echo "  Demo JWT (CUSTOMER, $DEFAULT_CUSTOMER_ID):"
    echo "    $(mint_token CUSTOMER "$DEFAULT_CUSTOMER_ID" 2>/dev/null || echo '(mint failed — see ./dev.sh seed for diagnostics)')"
  fi
  echo
  echo "  Next: ./dev.sh seed     (wait for first ingestion cycle + example query)"
  echo "        ./dev.sh status   ./dev.sh logs -f"
  echo
}

cmd_stop() {
  local tls=0 volumes=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --tls) tls=1; shift ;;
      --volumes|-v) volumes=1; shift ;;
      *) log_err "Unknown option for stop: $1"; exit 1 ;;
    esac
  done
  compose_context "$tls"

  if [[ "$volumes" -eq 1 ]]; then
    log_warn "This deletes the Postgres data volume (all local demo data). Continue? [y/N]"
    read -r -p "> " confirm
    if [[ "$confirm" != "y" && "$confirm" != "Y" ]]; then
      log_info "Aborted."
      return 0
    fi
    compose down -v --remove-orphans
    log_ok "Stack stopped, volumes removed."
  else
    compose down --remove-orphans
    log_ok "Stack stopped (data volume kept — use 'stop --volumes' to wipe it)."
  fi
}

cmd_restart() {
  # stop only understands --tls (not --build/--wait-timeout), so scan for it
  # rather than forwarding start's full flag set to stop verbatim.
  local tls=0
  for arg in "$@"; do
    [[ "$arg" == "--tls" ]] && tls=1
  done
  if [[ "$tls" -eq 1 ]]; then
    cmd_stop --tls
  else
    cmd_stop
  fi
  cmd_start "$@"
}

cmd_status() {
  local tls=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --tls) tls=1; shift ;;
      *) log_err "Unknown option for status: $1"; exit 1 ;;
    esac
  done
  compose_context "$tls"

  echo "Containers:"
  compose ps
  echo

  if curl_json "$BASE_URL/actuator/health" -o /tmp/dev-sh-health.json 2>/dev/null; then
    if command -v jq >/dev/null 2>&1; then
      log_ok "API health ($BASE_URL): $(jq -r '.status' /tmp/dev-sh-health.json)"
    else
      log_ok "API health ($BASE_URL): reachable (install jq for a parsed summary)"
    fi
  else
    log_warn "API not reachable at $BASE_URL. Is the stack started? ./dev.sh start"
    rm -f /tmp/dev-sh-health.json
    return 0
  fi
  rm -f /tmp/dev-sh-health.json

  # /actuator/health shows no per-source detail at the default show-details
  # setting (never, for anonymous callers) — /v1/admin/sources is the real
  # source of truth for ingestion status, so use that instead.
  if [[ -f "$ENV_FILE" ]] && command -v node >/dev/null 2>&1; then
    load_env
    local admin_token
    if admin_token="$(mint_token ADMIN "$DEFAULT_CUSTOMER_ID" 2>/dev/null)"; then
      echo "Source sync status:"
      if command -v jq >/dev/null 2>&1; then
        curl_json -H "Authorization: Bearer $admin_token" "$BASE_URL/v1/admin/sources" 2>/dev/null \
          | jq -r '.sources[]? | "  \(.id): \(.status)  (freshness: \(.freshnessStatus // "n/a"))"' \
          || log_warn "Could not reach /v1/admin/sources."
      else
        curl_json -H "Authorization: Bearer $admin_token" "$BASE_URL/v1/admin/sources" 2>/dev/null || true
        echo
      fi
    fi
  fi
}

cmd_logs() {
  local follow=0 tail=200 tls=0
  local services=()
  while [[ $# -gt 0 ]]; do
    case "$1" in
      -f|--follow) follow=1; shift ;;
      --tail) tail="$2"; shift 2 ;;
      --tls) tls=1; shift ;;
      *) services+=("$1"); shift ;;
    esac
  done
  compose_context "$tls"
  local args=(logs --tail "$tail")
  [[ "$follow" -eq 1 ]] && args+=(-f)
  compose "${args[@]}" "${services[@]}"
}


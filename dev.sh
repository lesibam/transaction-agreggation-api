cmd_seed() {
  local timeout=90 tls=0 customer_id="$DEFAULT_CUSTOMER_ID"
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --timeout) timeout="$2"; shift 2 ;;
      --tls) tls=1; shift ;;
      --customer-id) customer_id="$2"; shift 2 ;;
      *) log_err "Unknown option for seed: $1"; exit 1 ;;
    esac
  done
  require_cmd node
  require_cmd curl
  compose_context "$tls"
  load_env

  log_info "Waiting for $BASE_URL/actuator/health ..."
  local waited=0
  until curl -fsS $CURL_TLS_FLAG "$BASE_URL/actuator/health" >/dev/null 2>&1; do
    if [[ "$waited" -ge "$timeout" ]]; then
      log_err "API did not become healthy within ${timeout}s. Try: ./dev.sh logs transaction-api"
      exit 1
    fi
    sleep 3; waited=$((waited + 3))
  done
  log_ok "API is healthy."

  log_info "Minting an ADMIN token and waiting for every source to complete an ingestion cycle" \
           "(the scheduler runs every APP_INGESTION_INTERVAL_MS, 60s by default)..."
  local admin_token
  admin_token="$(mint_token ADMIN "$customer_id")"

  waited=0
  local all_success=0
  while [[ "$waited" -lt "$timeout" ]]; do
    local body
    body="$(curl -fsS $CURL_TLS_FLAG -H "Authorization: Bearer $admin_token" "$BASE_URL/v1/admin/sources" || echo '{}')"
    if command -v jq >/dev/null 2>&1; then
      if [[ "$(echo "$body" | jq -r '[.sources[]?.status] | all(. == "SUCCESS") and (length > 0)')" == "true" ]]; then
        all_success=1
        break
      fi
    else
      # Without jq, fall back to a crude but effective substring check.
      if echo "$body" | grep -q '"status":"SUCCESS"' && ! echo "$body" | grep -q '"status":"INITIAL"\|"status":"FAILED"'; then
        all_success=1
        break
      fi
    fi
    sleep 5; waited=$((waited + 5))
  done

  if [[ "$all_success" -eq 1 ]]; then
    log_ok "All configured sources report SUCCESS."
  else
    log_warn "Timed out after ${timeout}s waiting for all sources to succeed — showing current status anyway:"
  fi
  if command -v jq >/dev/null 2>&1; then
    curl -fsS $CURL_TLS_FLAG -H "Authorization: Bearer $admin_token" "$BASE_URL/v1/admin/sources" | jq .
  else
    curl -fsS $CURL_TLS_FLAG -H "Authorization: Bearer $admin_token" "$BASE_URL/v1/admin/sources"
    echo
  fi

  log_info "Querying the seeded demo customer ($customer_id) as a taste of the data:"
  local customer_token
  customer_token="$(mint_token CUSTOMER "$customer_id")"
  if command -v jq >/dev/null 2>&1; then
    curl -fsS $CURL_TLS_FLAG -H "Authorization: Bearer $customer_token" \
      "$BASE_URL/v1/customers/$customer_id/transactions?limit=5" | jq .
  else
    curl -fsS $CURL_TLS_FLAG -H "Authorization: Bearer $customer_token" \
      "$BASE_URL/v1/customers/$customer_id/transactions?limit=5"
    echo
  fi

  echo
  log_ok "Demo data is flowing. Reusable tokens:"
  echo "  CUSTOMER: $customer_token"
  echo "  ADMIN:    $admin_token"
  echo
  echo "  curl -H \"Authorization: Bearer \$TOKEN\" \"$BASE_URL/v1/customers/$customer_id/summary\""
}


# AdminSourcesEndpointTest, ApiIsolationTest, ApiPaginationAndFilterTest,
# ApiSummaryCurrencyTest, and ApiValidationTest are also excluded for the same
# reason (@SpringBootTest / Testcontainers KafkaContainer / GenericContainer).
# SourceAdapterNormalizationTest no longer exists post-ADR-011 (config-driven
# source registry, landed on main 2026-09-25) — replaced by SourceNormalizerTest
# plus the per-transport tests below.
UNIT_ONLY_TESTS="KeysetCursorTest,ResilienceTest,QuarantineTest,SyncFailureTest,RuleBasedCategorizerTest,CustomerAccessValidatorTest,SourceNormalizerTest,HttpTransactionSourceTest,MockTransactionSourceTest,SyncHealthIndicatorTest"

cmd_test() {
  local mode="full"
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --unit) mode="unit"; shift ;;
      --e2e) mode="e2e"; shift ;;
      *) log_err "Unknown option for test: $1"; exit 1 ;;
    esac
  done

  case "$mode" in
    unit)
      require_cmd mvn
      log_info "Running the Testcontainers-free subset (no Docker required)..."
      exec "$ROOT/scripts/test.sh" -q test -Dtest="$UNIT_ONLY_TESTS" -DfailIfNoTests=false
      ;;
    full)
      log_info "Running the full suite (unit + Testcontainers integration; needs Docker)..."
      exec "$ROOT/scripts/test.sh" test
      ;;
    e2e)
      require_cmd node
      require_cmd npm
      log_info "Running Playwright E2E against a running stack at \$E2E_BASE_URL (default http://localhost:8080)."
      log_info "Make sure the stack is started first: ./dev.sh start && ./dev.sh seed"
      npm ci
      npx playwright install --with-deps chromium
      set +e
      npx playwright test --reporter=json > "$ROOT/playwright-results.json"
      set -e
      # Pass/fail is decided by e2e-assert.mjs (checks real failures AND
      # skips), not Playwright's own exit code — see its header comment and
      # docs/principal_engineer_review_report.md C-01.
      node "$ROOT/scripts/e2e-assert.mjs" "$ROOT/playwright-results.json"
      ;;
  esac
}


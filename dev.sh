main() {
  local cmd="${1:-help}"
  [[ $# -gt 0 ]] && shift

  case "$cmd" in
    setup) cmd_setup "$@" ;;
    certs) cmd_certs "$@" ;;
    start) cmd_start "$@" ;;
    stop) cmd_stop "$@" ;;
    restart) cmd_restart "$@" ;;
    status) cmd_status "$@" ;;
    logs) cmd_logs "$@" ;;
    seed|setup-data) cmd_seed "$@" ;;
    test) cmd_test "$@" ;;
    perf|load-test) cmd_perf "$@" ;;
    clean) cmd_stop --volumes "$@" ;;
    help|-h|--help) cmd_help ;;
    *)
      log_err "Unknown command: $cmd"
      cmd_help
      exit 1
      ;;
  esac
}

main "$@"

#!/usr/bin/env bash
#
# dev.sh — single entrypoint for local development and demo of Transact.
#
# Wraps docker compose, Maven, Node/Playwright, and (optionally) k6 so a
# fresh clone can go from zero to a running, demonstrable stack with one
# command, without memorizing the individual tool invocations documented in
# README.md.
#
# Usage: ./dev.sh <command> [options]
#
# Run './dev.sh help' for the full command list.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

ENV_FILE="$ROOT/.env"
CERT_DIR="$ROOT/certs"
COMPOSE_BASE=(-f docker-compose.yml)
COMPOSE_TLS=(-f docker-compose.yml -f docker-compose.tls.yml)
DEFAULT_CUSTOMER_ID="00000000-0000-0000-0000-000000000001"

# ---------------------------------------------------------------------------
# Output helpers
# ---------------------------------------------------------------------------

if [[ -t 1 ]] && [[ -z "${NO_COLOR:-}" ]]; then
  C_INFO=$'\033[36m'; C_OK=$'\033[32m'; C_WARN=$'\033[33m'; C_ERR=$'\033[31m'; C_RESET=$'\033[0m'
else
  C_INFO=""; C_OK=""; C_WARN=""; C_ERR=""; C_RESET=""
fi

log_info() { printf '%s[dev.sh]%s %s\n' "$C_INFO" "$C_RESET" "$*"; }
log_ok()   { printf '%s[dev.sh]%s %s\n' "$C_OK" "$C_RESET" "$*"; }
log_warn() { printf '%s[dev.sh]%s %s\n' "$C_WARN" "$C_RESET" "$*" >&2; }
log_err()  { printf '%s[dev.sh]%s %s\n' "$C_ERR" "$C_RESET" "$*" >&2; }

require_cmd() {
  local cmd="$1" hint="${2:-}"
  if ! command -v "$cmd" >/dev/null 2>&1; then
    log_err "Required tool '$cmd' not found on PATH.${hint:+ $hint}"
    exit 1
  fi
}

# ---------------------------------------------------------------------------
# Environment / compose plumbing
# ---------------------------------------------------------------------------

# Idempotent: writes .env with fresh dev-only secrets only if it doesn't
# already exist. Never overwrites — a hand-edited .env is left alone.
ensure_env_file() {
  if [[ -f "$ENV_FILE" ]]; then
    return 0
  fi
  require_cmd openssl "Install openssl to auto-generate dev secrets, or copy .env.example to .env by hand."
  log_info "No .env found — generating one with fresh dev-only secrets (never committed; see .gitignore)."
  local pg_password jwt_secret
  pg_password="$(openssl rand -hex 24)"
  jwt_secret="$(openssl rand -base64 48 | tr -d '\n')"
  cat > "$ENV_FILE" <<EOF
# Generated by ./dev.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) — dev-only secrets. Never commit this file.
# Regenerate at any time by deleting .env and re-running ./dev.sh setup (or start).
POSTGRES_PASSWORD=$pg_password
SPRING_DATASOURCE_PASSWORD=$pg_password
APP_SECURITY_JWT_SECRET=$jwt_secret
APP_INGESTION_INTERVAL_MS=60000
EOF
  log_ok "Wrote $ENV_FILE"
}

# Sources .env into the current shell so this script can mint JWTs with the
# same secret the running server uses (scripts/mint-jwt.mjs otherwise falls
# back to a hard-coded test secret — see docs/principal_engineer_review_report.md L-03).
load_env() {
  if [[ ! -f "$ENV_FILE" ]]; then
    log_err "No .env found. Run './dev.sh setup' first."
    exit 1
  fi
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a
}

# Populates the global COMPOSE_FILES array and BASE_URL for the given TLS flag.
compose_context() {
  local tls="$1"
  if [[ "$tls" == "1" ]]; then
    COMPOSE_FILES=("${COMPOSE_TLS[@]}")
    BASE_URL="https://localhost:8443"
    CURL_TLS_FLAG="-k"
  else
    COMPOSE_FILES=("${COMPOSE_BASE[@]}")
    BASE_URL="http://localhost:8080"
    CURL_TLS_FLAG=""
  fi
}

compose() {
  docker compose "${COMPOSE_FILES[@]}" "$@"
}

require_certs() {
  if [[ ! -f "$CERT_DIR/localhost.p12" ]]; then
    log_err "No local TLS certs found at $CERT_DIR. Run './dev.sh certs' first."
    exit 1
  fi
}

mint_token() {
  # $1=roles (CUSTOMER|ADMIN), $2=customerId
  E2E_ROLES="$1" E2E_CUSTOMER_ID="$2" node "$ROOT/scripts/mint-jwt.mjs"
}

curl_json() {
  curl -fsS $CURL_TLS_FLAG "$@"
}

